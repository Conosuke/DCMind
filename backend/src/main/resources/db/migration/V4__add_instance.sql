/*
  인스턴스 데이터 테이블 생성
    * sop_instance_uid: DICOM 하나의 인스턴스 고유 식별자
    * UNIQUE 제약 조건을 통해 중복된 인스턴스를 방지
    * REFERENCES series(id) - instance 테이블의 series_id 컬럼은 series 테이블의 id 컬럼을 참조하여 외래 키 제약 조건을 설정
*/
CREATE TABLE instance (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sop_instance_uid    VARCHAR(64) NOT NULL UNIQUE,
    series_id           BIGINT      NOT NULL REFERENCES series(id),
    rows                INT,
    columns             INT,
    bits_allocated      INT,
    transfer_syntax_uid VARCHAR(64),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
