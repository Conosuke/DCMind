/*
  시리즈 데이터 테이블 생성
    * series_instance_uid: DICOM 시리즈의 고유 식별자
    * UNIQUE 제약 조건을 통해 중복된 시리즈를 방지
    * REFERENCES study(id) - series 테이블의 study_id 컬럼은 study 테이블의 id 컬럼을 참조하여 외래 키 제약 조건을 설정
*/
CREATE TABLE series (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_instance_uid VARCHAR(64) NOT NULL UNIQUE,
    modality            VARCHAR(16),
    study_id            BIGINT      NOT NULL REFERENCES study(id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
